void oled_display_text(i2c_master_dev_handle_t dev_handle, int line, const char *text)
{
    if (line < 0 || line > 7) return;

    
    uint8_t set_page_cmds[] = {
        0x00,
        0xB0 | line,
        0x00,
        0x10
    };
    i2c_master_transmit(dev_handle, set_page_cmds, sizeof(set_page_cmds), pdMS_TO_TICKS(1000));

    int len = strlen(text);
    uint8_t data_buf[128];
    data_buf[0] = 0x40; 

    int cursor = 1;
    for (int i = 0; i < len && cursor < 123; i++) {
        unsigned char c = text[i];
        
        // Automatska konverzija naših č/ć/š/đ karaktera u obična slova da ne pukne ispis
        if (c == 0xC4 || c == 0xC5 || c == 0xC3) { // UTF-8 prefiksi za naša slova
            i++; // Preskoči drugi bajt UTF-8 karaktera
            c = 'c'; // Zamena po potrebi
        }

        const uint8_t *glyph = font5x7[(int)c];
        if (!glyph) {
            glyph = font5x7['?']; 
        }

        for (int j = 0; j < 5; j++) {
            data_buf[cursor++] = glyph[j];
        }
        data_buf[cursor++] = 0x00; 
    }

    while (cursor < 128) {
        data_buf[cursor++] = 0x00;
    }

    i2c_master_transmit(dev_handle, data_buf, 128, pdMS_TO_TICKS(1000));
}