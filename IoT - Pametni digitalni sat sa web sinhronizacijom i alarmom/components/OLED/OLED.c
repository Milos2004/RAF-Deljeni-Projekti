static void send_cmd(i2c_master_dev_handle_t dev, uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_master_transmit(dev, buf, sizeof(buf), 1000);
}

void oled_init(i2c_master_dev_handle_t *out_dev_handle) {
    i2c_master_bus_config_t bus_config = {
        .i2c_port = I2C_PORT,
        .sda_io_num = PIN_SDA,
        .scl_io_num = PIN_SCL,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .flags.enable_internal_pullup = true,
    };
    i2c_master_bus_handle_t bus_handle;
    ESP_ERROR_CHECK(i2c_new_master_bus(&bus_config, &bus_handle));

    i2c_device_config_t dev_config = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = OLED_ADDR,
        .scl_speed_hz = 100000,
    };
    ESP_ERROR_CHECK(i2c_master_bus_add_device(bus_handle, &dev_config, out_dev_handle));

    send_cmd(*out_dev_handle, 0xAE);
    send_cmd(*out_dev_handle, 0xD5); send_cmd(*out_dev_handle, 0x80);
    send_cmd(*out_dev_handle, 0xA8); send_cmd(*out_dev_handle, 0x3F);
    send_cmd(*out_dev_handle, 0xD3); send_cmd(*out_dev_handle, 0x00);
    send_cmd(*out_dev_handle, 0x40);
    send_cmd(*out_dev_handle, 0x8D); send_cmd(*out_dev_handle, 0x14);
    send_cmd(*out_dev_handle, 0x20); send_cmd(*out_dev_handle, 0x02); 
    send_cmd(*out_dev_handle, 0xA1); send_cmd(*out_dev_handle, 0xC8);
    send_cmd(*out_dev_handle, 0xDA); send_cmd(*out_dev_handle, 0x12);
    send_cmd(*out_dev_handle, 0x81); send_cmd(*out_dev_handle, 0xCF);
    send_cmd(*out_dev_handle, 0xAF);

    gpio_config_t io_conf = {
        .pin_bit_mask = (1ULL << ENC_CLK) | (1ULL << ENC_DT),
        .mode = GPIO_MODE_INPUT,
        .pull_up_en = GPIO_PULLUP_ENABLE,
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
        .intr_type = GPIO_INTR_DISABLE
    };
    gpio_config(&io_conf);

    s_last_clk = gpio_get_level(ENC_CLK);
}

